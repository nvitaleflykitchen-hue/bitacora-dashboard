begin;
lock table equipo.reclutamiento_solicitudes in access exclusive mode;
alter table equipo.reclutamiento_solicitudes
  add column numero_requerimiento bigint generated by default as identity,
  add column codigo_requerimiento text,
  add column fecha_necesidad date;

-- Numerar el historial sin alterar updated_at ni ningún dato de negocio.
alter table equipo.reclutamiento_solicitudes disable trigger trg_reclutamiento_solicitudes_updated_at;
with numerados as (
  select id, row_number() over(order by fecha_apertura, created_at, id) as numero
  from equipo.reclutamiento_solicitudes
)
update equipo.reclutamiento_solicitudes s
set numero_requerimiento=n.numero,
    codigo_requerimiento='REQ-PER-'||extract(year from s.fecha_apertura)::text||'-'||lpad(n.numero::text,greatest(4,length(n.numero::text)),'0')
from numerados n where s.id=n.id;
alter table equipo.reclutamiento_solicitudes enable trigger trg_reclutamiento_solicitudes_updated_at;
select setval(pg_get_serial_sequence('equipo.reclutamiento_solicitudes','numero_requerimiento'),greatest(coalesce(max(numero_requerimiento),0),1),count(*)>0)
from equipo.reclutamiento_solicitudes;
alter table equipo.reclutamiento_solicitudes
  alter column numero_requerimiento set generated always,
  alter column codigo_requerimiento set not null,
  add constraint reclutamiento_numero_unico unique(numero_requerimiento),
  add constraint reclutamiento_codigo_unico unique(codigo_requerimiento);

create function equipo.asignar_codigo_requerimiento() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
  if tg_op='INSERT' then
    new.codigo_requerimiento := 'REQ-PER-'||extract(year from new.fecha_apertura)::text||'-'||lpad(new.numero_requerimiento::text,greatest(4,length(new.numero_requerimiento::text)),'0');
  elsif new.numero_requerimiento is distinct from old.numero_requerimiento
     or new.codigo_requerimiento is distinct from old.codigo_requerimiento then
    raise exception 'El código del requerimiento es permanente y no se puede modificar';
  end if;
  return new;
end $$;
create trigger asignar_codigo_requerimiento before insert or update on equipo.reclutamiento_solicitudes
for each row execute function equipo.asignar_codigo_requerimiento();
comment on column equipo.reclutamiento_solicitudes.codigo_requerimiento is 'Código permanente REQ-PER-año de apertura-número global. Históricos ordenados por apertura/creación/UUID. No se reinicia anualmente.';
notify pgrst,'reload schema';
commit;
